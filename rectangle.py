
def area(a, b): 
    '''
    Возвращает площадь прямоугольника со сторонами a, b
        area(a, b)
    Параметры
        a (int): сторона прямоугольника
        b (int): сторона прямоугольника
    '''
    return a * b 


def perimeter(a, b): 
    '''
    Возвращает периметр прямоугольника со сторонами a, b
        perimeter(a, b)
    Параметры
        a (int): сторона прямоугольника
        b (int): сторона прямоугольника
    '''
    return (a+b)*2 